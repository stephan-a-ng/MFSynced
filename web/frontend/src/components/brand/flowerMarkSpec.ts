/**
 * Moon Five flower mark geometry — extracted verbatim from the design bundle
 * (`Moon Five Design.fig` → `flower-mark.js`). Two Figma states, DEFAULT and
 * HOVER, with identical node trees; FlowerMark interpolates between them.
 *
 * GENERATED — do not hand-edit. Every node pairs 1:1 by position with its
 * twin in the other state, and every path command pairs 1:1 by index, which
 * is what makes a straight per-number lerp valid.
 */

/** One SVG path command: the letter, then its numeric arguments. */
export type FlowerPathCommand = [string, ...number[]];

export interface FlowerNode {
  name: string;
  /** Figma affine transform [a, b, c, d, e, f]. */
  matrix: number[];
  /** [width, height] — the box the matrix is applied about. */
  size: number[];
  opacity: number;
  /** Present on leaf VECTOR nodes; absent on group/frame nodes. */
  paths?: FlowerPathCommand[][];
  /**
   * The node's own fill from the .fig — ink `#141303` everywhere except the
   * inner disc's brand yellow `#fcd01b`.
   *
   * `FlowerMark` overrides this with a single colour by default (the mark is
   * monochrome at small sizes), but the two-colour original is what makes the
   * bloom legible when rendered large: flattened to one ink, the open state's
   * disc and the six shapes on top of it merge into a solid blob.
   */
  fill?: string;
  children?: FlowerNode[];
}

